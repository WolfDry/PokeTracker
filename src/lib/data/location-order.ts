/** Groupes de versions (slugs PokeAPI) qui parcourent une région dans un autre ordre. */
const VERSION_GROUP_ORDERS: Record<string, Partial<Record<Region, string[]>>> = {
  "gold-silver": { kanto: KANTO_FROM_JOHTO },
  crystal: { kanto: KANTO_FROM_JOHTO },
  "heartgold-soulsilver": { kanto: KANTO_FROM_JOHTO },
  "black-2-white-2": { unova: UNOVA_B2W2 },
};

/** Rang de chaque lieu dans la progression d'un groupe de versions : régions dans l'ordre des générations. */
export function locationRanks(versionGroupSlug: string): Map<string, number> {
  const orders = { ...REGION_ORDERS, ...VERSION_GROUP_ORDERS[versionGroupSlug] };
  const ranks = new Map<string, number>();
  for (const slug of Object.values(orders).flat()) if (!ranks.has(slug)) ranks.set(slug, ranks.size);
  return ranks;
}
